#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {JSDOM}=require('jsdom');
const base=path.resolve('app/src/main/assets');
const d=new JSDOM(fs.readFileSync(path.join(base,'field-guide.html'),'utf8'),{url:'https://ghc.local/',runScripts:'outside-only',pretendToBeVisual:true});
const w=d.window;w.scrollTo=()=>{};
w.eval(fs.readFileSync(path.join(base,'field-guide-data.js'),'utf8'));
w.eval(fs.readFileSync(path.join(base,'field-guide.js'),'utf8'));
const doc=w.document;
assert.equal(w.GHC_FIELD_GUIDE.count,19);
assert.equal(doc.querySelectorAll('.tile').length,19,'All animals should render');
const query=doc.querySelector('#query');query.value='Frischling';query.dispatchEvent(new w.Event('input',{bubbles:true}));
assert.equal(doc.querySelectorAll('.tile').length,1,'Search should match boar terms');
query.value='';query.dispatchEvent(new w.Event('input',{bubbles:true}));
doc.querySelector('[data-filter="Schalenwild"]').click();
assert.equal(doc.querySelectorAll('.tile').length,6,'Six ungulate entries');
doc.querySelector('[data-filter="All"]').click();
doc.querySelector('[data-open="roe"]').click();
assert(!doc.querySelector('#detail').classList.contains('hidden'),'Card opens');
assert(doc.querySelector('#animalContent').textContent.includes('Rehwild'),'Card info renders');
doc.querySelector('#animalNotes').value='Tracks along hedgerow';
doc.querySelector('#saveNote').click();
assert.equal(JSON.parse(w.localStorage.getItem('ghc-field-notes-v1')).roe,'Tracks along hedgerow','Notes saved locally');
doc.querySelector('#favorite').click();
assert(JSON.parse(w.localStorage.getItem('ghc-field-favorites-v1')).roe,'Favorite persists');
assert.equal(w.fieldGuideHandleBack(),true,'System Back closes detail');
assert.equal(w.fieldGuideHandleBack(),false,'System Back leaves root handling to Android');
doc.querySelector('#showSafety').click();
assert(doc.querySelector('#safety').textContent.includes('Trichinella'),'Safety panel available');
assert.equal(w.fieldGuideHandleBack(),true,'System Back closes safety');
assert.equal(doc.querySelectorAll('.tile').length,19,'List retained');
d.window.close();
console.log('PASS: offline field guide DOM search, filters, card, notes, favorite, safety and Back');
