#!/usr/bin/env node
/* Real app data assertions plus explicitly SYNTHETIC evaluator transition fixtures. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {JSDOM}=require('jsdom');
const dir=path.resolve('app/src/main/assets'),read=n=>fs.readFileSync(path.join(dir,n),'utf8');
const engine=require(path.join(dir,'season-engine.js'));
const context={window:{}};vm.runInNewContext(read('state-season-data.js'),context);vm.runInNewContext(read('germany-map-data.js'),context);
const data=context.window.GHC_SEASON_DATA,map=context.window.GHC_MAP_SHAPES;
assert.equal(data.states.length,16,'Must list all 16 Bundesländer');
assert.equal(new Set(data.states.map(s=>s.code)).size,16);
assert.equal(map.states.length,16,'Must bundle exactly 16 actual vector state paths');
assert.deepEqual(new Set(map.states.map(s=>s.code)),new Set(data.states.map(s=>s.code)));
assert(map.states.every(s=>s.d.length>10),'Map must contain geometric path for each state');
for(const code of ['DE-BE','DE-HB','DE-HH'])assert(map.states.find(s=>s.code===code),'City state missing');
assert.equal(Object.keys(data.hessen.species).length,19,'Every existing animal mapped or marked unknown');
for(const s of data.states.filter(s=>s.code!=='DE-HE')){
 for(const id of Object.keys(data.hessen.species))assert.equal(engine.evaluate(data,s.code,id,null,'2026-10-26').status,engine.UNKNOWN);
}
for(const id of ['heron','auer','wildcat'])assert.equal(engine.evaluate(data,'DE-HE',id,null,'2026-10-26').status,engine.UNKNOWN);
const season=(id,klass,date)=>engine.evaluate(data,'DE-HE',id,klass,date).status;
assert.equal(season('roe',null,'2026-10-26'),engine.CONDITIONAL);
assert.equal(season('roe','buck','2026-04-01'),engine.OPEN);
assert.equal(season('roe','buck','2026-03-31'),engine.UNKNOWN,'Dates before 1 April amendment cannot use 2026 source');
assert.equal(season('roe','doe-kid','2026-08-31'),engine.CLOSED);
assert.equal(season('roe','doe-kid','2026-09-01'),engine.OPEN);
assert.equal(season('red','yearling','2027-01-31'),engine.OPEN);
assert.equal(season('red','yearling','2027-02-01'),engine.CLOSED);
assert.equal(season('red','yearling','2027-04-01'),engine.OPEN);
assert.equal(season('red','yearling','2027-04-26'),engine.OPEN);
assert.equal(season('red','yearling','2027-04-27'),engine.UNKNOWN,'Review expiry must turn unknown');
assert.equal(season('pheasant','hen','2026-10-26'),engine.NO_GENERAL);
assert.equal(season('pheasant',null,'2026-10-26'),engine.CONDITIONAL);
assert.equal(season('hare','general','2026-10-26'),engine.CONDITIONAL,'Population caveat must not yield green');
assert.equal(season('mallard','general','2026-10-26'),engine.CONDITIONAL);
assert.equal(season('fox',null,'2026-10-26'),engine.OPEN);
assert.equal(season('raccoon',null,'2026-10-26'),engine.OPEN);
assert.equal(season('magpie',null,'2026-10-26'),engine.OPEN);
assert.equal(season('pigeon',null,'2026-10-26'),engine.CONDITIONAL);
assert.equal(season('pigeon','juvenile','2026-10-26'),engine.OPEN);
assert.equal(season('pigeon','adult','2026-10-26'),engine.CLOSED);
// Synthetic only — these do NOT represent any state hunting law.
const synthetic=JSON.parse(JSON.stringify(data));
synthetic.hessen.species.synthetic={classes:[{id:'x',label:'Synthetic',intervals:[['11-15','02-29']]}]};
assert.equal(engine.evaluate(synthetic,'DE-HE','synthetic','x','2026-11-15').status,engine.OPEN);
assert.equal(engine.evaluate(synthetic,'DE-HE','synthetic','x','2027-02-28').status,engine.OPEN);
assert.equal(engine.matchesRange('02-29',['11-15','02-29']),true);
assert.equal(engine.matchesRange('03-01',['11-15','02-29']),false);
synthetic.hessen.species.synthetic.conflict=true;
assert.equal(engine.evaluate(synthetic,'DE-HE','synthetic','x','2026-11-15').status,engine.UNKNOWN);
assert(!engine.validDate('2027-02-29')&&engine.validDate('2028-02-29'));
const dom=new JSDOM(read('field-guide.html'),{url:'https://ghc.local/',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window;w.scrollTo=function(){};
for(const f of ['field-guide-data.js','jungjaeger-data.js','germany-map-data.js','state-season-data.js','season-engine.js','field-guide.js','state-map-controller.js'])w.eval(read(f));
const d=w.document,guide=w.GHC_STATE_GUIDE;
assert.equal(guide.getPage(),'map','Home must be state map');
assert.equal(d.querySelectorAll('svg [data-state]').length,16);
assert.equal(d.querySelectorAll('#stateChoices button').length,16);
d.querySelector('#stateChoices [data-state="DE-BE"]').click();
assert.equal(guide.getState(),'DE-BE');
assert.equal(guide.getPage(),'stateHome');
assert.equal(w.localStorage.getItem('ghc-selected-bundesland-v1'),'DE-BE');
guide.openSection('animals');
assert.equal(guide.getPage(),'browse');
assert.equal(d.querySelectorAll('.tile').length,19);
assert(d.querySelectorAll('.tile.season-unknown-or-stale').length===19,'Unverified state must never show green');
d.querySelector('[data-open="fox"]').click();
assert.equal(guide.getPage(),'detail');
assert(d.querySelector('#animalContent .seasonStrip').textContent.includes('Not verified'));
assert.equal(w.fieldGuideHandleBack(),true);
assert.equal(guide.getPage(),'browse');
assert.equal(w.fieldGuideHandleBack(),true);
assert.equal(guide.getPage(),'stateHome');
assert.equal(w.fieldGuideHandleBack(),true);
assert.equal(guide.getPage(),'map');
guide.chooseState('DE-HE');
guide.openSection('animals');
assert(d.querySelector('[data-open="fox"]').classList.contains('season-general-window-open'),'Green tile for verified general fox calendar');
assert(d.querySelector('[data-open="roe"]').classList.contains('season-conditional'),'Age/sex uncertainty must remain amber');
d.querySelector('[data-open="roe"]').click();
assert(d.querySelector('#animalContent .seasonStrip').textContent.includes('class'));
d.querySelector('#legalClass').value='doe-kid';
d.querySelector('#legalClass').dispatchEvent(new w.Event('change',{bubbles:true}));
assert.equal(d.querySelector('#animalContent .sheet').classList.contains('season-general-window-open'),true);
assert(d.querySelector('#animalContent .seasonStrip').textContent.includes('Reviewed:'));
d.querySelector('#animalNotes').value='Do not erase saved notes';
d.querySelector('#saveNote').click();
d.querySelector('#favorite').click();
assert(JSON.parse(w.localStorage.getItem('ghc-field-favorites-v1')).roe);
assert.equal(JSON.parse(w.localStorage.getItem('ghc-field-notes-v1')).roe,'Do not erase saved notes');
guide.openSection('knowledge');
assert.equal(d.querySelectorAll('.chapterTile').length,41);
guide.openSection('methods');
assert(d.querySelectorAll('.chapterTile').length===7);
guide.openSection('seasons');
assert.equal(d.querySelectorAll('#seasonList .seasonEntry').length,19);
guide.openSection('state');
assert(d.querySelector('#stateRulesContent').textContent.includes('HJagdV'));
assert(d.querySelector('#archiveLink').getAttribute('href')==='index.html');
assert(d.querySelector('#germanyMap').textContent!==null);
assert(!/<script[^>]+src="https?:\/\//i.test(read('field-guide.html')),'No external runtime scripts');
for(const f of ['germany-map-data.js','state-season-data.js','season-engine.js','state-map-controller.js'])assert(read('field-guide.html').includes(f),'Offline script not linked: '+f);
assert.equal(w.GHC_FIELD_GUIDE.handbookCount,41);
dom.window.close();
console.log('PASS: 16 vector states, Berlin/Bremen/Hamburg selection, source-specific class dates, unknown safety, 19 animals, 41 references, persistence, notes, favorites, Back and offline scripts');
