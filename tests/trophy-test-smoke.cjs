const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('jsdom');
const base=path.resolve('app/src/main/assets');
const html=fs.readFileSync(path.join(base,'trophy-test.html'),'utf8');
const js=fs.readFileSync(path.join(base,'trophy-test-app.js'),'utf8');
const data=fs.readFileSync(path.join(base,'trophy-test-data.js'),'utf8');
const dom=new JSDOM(html,{url:'https://ghc.local/trophy-test.html',runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window;
w.HTMLElement.prototype.scrollIntoView=function(){};
w.eval(data);
w.eval(js);
const app=w.GHC_TROPHY_TEST;
assert.equal(app.cards.length,29);
assert.equal(app.scored.length,19);
assert.equal(app.cards.filter(x=>x.certainty==='review').length,10);
assert(w.document.body.textContent.includes('Trophy Test'));
assert.equal(w.document.querySelectorAll('[data-specimen]').length,29);
w.document.querySelector('[data-specimen="mouflon"]').click();
assert(w.document.querySelector('.card h2').textContent.includes('Muffelwild'));
app.setMode('flash');
assert(w.document.querySelector('.card h2').textContent.includes('Identify'));
assert(!w.document.querySelector('.card .heading').textContent.includes('Rehwild'),'flash front should not show answer names');
w.document.querySelector('#reveal').click();
assert(w.document.querySelector('.card h2').textContent.length>2);
w.document.querySelector('[data-score="ok"]').click();
assert.equal(Object.values(app.progress).reduce((a,b)=>a+b.tries,0),1);
app.setMode('quiz');
assert.equal(w.document.querySelectorAll('[data-answer]').length,4);
assert(w.document.querySelector('.card h2').textContent.includes('Identify'));
const before=Object.values(app.progress).reduce((a,b)=>a+b.tries,0);
w.document.querySelector('[data-answer]').click();
assert(w.document.querySelector('.feedback'));
assert.equal(Object.values(app.progress).reduce((a,b)=>a+b.tries,0),before+1);
w.document.querySelector('#nextQuestion').click();
assert.equal(w.document.querySelectorAll('[data-answer]').length,4);
assert(w.localStorage.getItem('ghc-trophy-test-progress-v1'));
assert.equal(w.localStorage.getItem('ghc-study-progress-v1'),null);
w.close();
console.log('PASS: Trophy cards, unconfirmed exclusion, quiz, reveal, separated progress, 29 images');
